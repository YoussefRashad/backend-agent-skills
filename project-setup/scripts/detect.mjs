// ---- installed skill copies ----------------------------------------------------
/** Directories named project-setup containing SKILL.md under base (bounded depth, links not followed). */
function scanSkillCopies(base, maxDepth) {
  const found = [];
  const stack = [{ dir: base, depth: 0 }];
  while (stack.length) {
    const { dir, depth } = stack.pop();
    let entries = [];
    try { entries = fs.readdirSync(dir, { withFileTypes: true }); } catch { continue; }
    for (const e of entries) {
      const full = path.join(dir, e.name);
      const linked = e.isSymbolicLink();
      let isDir = e.isDirectory();
      if (linked) { try { isDir = fs.statSync(full).isDirectory(); } catch { isDir = false; } } // dangling link = absent
      if (!isDir) continue;
      // A linked skill folder is a real installation (tools follow it); read-only discovery must report it.
      if (e.name === 'project-setup' && fs.existsSync(path.join(full, 'SKILL.md'))) found.push(full);
      else if (!linked && depth < maxDepth) stack.push({ dir: full, depth: depth + 1 }); // no recursion through links: no cycles
    }
  }
  return found;
}

function readJsonQuiet(p) { try { return readJsonFile(p); } catch { return null; } }

/** skillOverrides set to "off" in any Claude settings layer this session would load. */
/** The documented skillOverrides states. Anything else is invalid and must not change the effective value. */
const OVERRIDE_STATES = new Set(['on', 'off', 'name-only', 'user-invocable-only']);
const invalidOverrides = [];

/**
 * Keys whose EFFECTIVE skillOverrides value is "off". Values are merged per key in Claude Code's precedence order for
 * the layers read here (lowest first): user settings -> shared project settings -> project-local settings. A later
 * layer replaces an earlier value for the same key only with a documented value (on, off, name-only,
 * user-invocable-only, exact spelling). Invalid values (null, booleans, numbers, objects, other strings, other case or
 * whitespace) are skipped, so the lower valid value stays in effect, and they are reported in invalidOverrides.
 * Managed policy and command-line settings are not visible to this script and are not inferred.
 * The shared project layer is the value of the one checked read above (C7 plan 3.5): unsafe, protected, unreadable or
 * invalid shared settings contribute nothing and are never reopened here.
 */
function claudeOffOverrides() {
  const effective = new Map();
  const shared = sharedSettings.state === 'ok' ? sharedSettings.value : null;
  const layers = [['user', () => readJsonQuiet(path.join(claudeHome, 'settings.json'))], ['shared project', () => shared], ['project-local', () => readJsonQuiet(path.join(root, '.claude', 'settings.local.json'))]];
  for (const [layer, load] of layers) {
    const v = load();
    const o = v !== null && typeof v === 'object' ? v.skillOverrides : undefined;
    if (!o || typeof o !== 'object' || Array.isArray(o)) continue;
    for (const [k, v] of Object.entries(o)) {
      if (typeof v === 'string' && OVERRIDE_STATES.has(v)) effective.set(k, v);
      else invalidOverrides.push({ layer, key: k, value: v === null ? null : typeof v === 'string' ? v : typeof v });
    }
  }
  return new Set([...effective].filter(([, v]) => v === 'off').map(([k]) => k));
}

/** SKILL.md paths disabled through [[skills.config]] enabled=false in Codex config files. */
function codexDisabledSkills() {
  const byFile = {};
  let files = [];
  try { files = fs.readdirSync(codexHome).filter((f) => f === 'config.toml' || f.endsWith('.config.toml')); } catch { /* none */ }
  for (const f of files) {
    let text; try { text = fs.readFileSync(path.join(codexHome, f), 'utf8'); } catch { continue; }
    const { data } = parseToml(text);
    const list = Array.isArray(data?.skills?.config) ? data.skills.config : [];
    byFile[f] = list.filter((x) => x && x.enabled === false && typeof x.path === 'string').map((x) => canonicalPath(path.dirname(x.path)));
  }
  return byFile;
}

function findSkillInstalls() {
  // Each location belongs to exactly one tool. A conflict is two ACTIVE copies visible to the SAME tool;
  // one repo-level copy per tool (.claude/skills + .agents/skills) is the intended layout.
  // Nested folders are scanned because both tools load synced skills from subfolders (e.g. skills/synced/<id>/).
  const candidates = [
    ...scanSkillCopies(path.join(claudeHome, 'skills'), 4).map((dir) => ({ tool: 'claude', scope: /[\\/]synced[\\/]/.test(dir) ? 'synced' : 'user', dir })),
    ...scanSkillCopies(path.join(root, '.claude', 'skills'), 0).map((dir) => ({ tool: 'claude', scope: 'repo', dir })),
    ...scanSkillCopies(path.join(home, '.agents', 'skills'), 4).map((dir) => ({ tool: 'codex', scope: /[\\/]synced[\\/]/.test(dir) ? 'synced' : 'user', dir })),
    ...scanSkillCopies(path.join(codexHome, 'skills'), 4).map((dir) => ({ tool: 'codex', scope: 'user-legacy', dir })),
    ...scanSkillCopies(path.join(root, '.agents', 'skills'), 0).map((dir) => ({ tool: 'codex', scope: 'repo', dir })),
    ...scanSkillCopies(path.join(claudeHome, 'plugins'), 6).map((dir) => ({ tool: 'claude', scope: 'plugin', dir })),
  ];
  const off = claudeOffOverrides();
  const codexOff = codexDisabledSkills();
  const found = [];
  const seen = new Set();
  for (const c of candidates) {
    const canon = canonicalPath(c.dir);
    const key = `${c.tool}|${canon}`;
    if (seen.has(key)) continue; // same directory reached twice (e.g. CODEX_HOME == ~/.agents) is one copy
    seen.add(key);
    let ver = 'unknown';
    try { ver = fs.readFileSync(path.join(c.dir, 'VERSION'), 'utf8').trim(); } catch { ver = c.scope === 'plugin' ? 'plugin' : 'v1-or-unversioned'; }
    const disabledBy = [];
    let overrideNote = null;
    if (c.tool === 'claude') {
      // Runtime identities: user/repo skill = "project-setup"; skill synced from claude.ai = "anthropic-skills:project-setup".
      // Plugin skills are excluded from skillOverrides (Claude Code docs), so an override never disables them here.
      const identity = c.scope === 'synced' ? 'anthropic-skills:project-setup' : c.scope === 'plugin' ? null : 'project-setup';
      if (identity && off.has(identity)) disabledBy.push(`skillOverrides "${identity}": "off"`);
      if (c.scope === 'plugin' && [...off].some((k) => /:project-setup$/.test(k))) overrideNote = 'skillOverrides does not apply to plugin skills; disable the plugin or have its owner remove v1';
    } else {
      if ((codexOff['config.toml'] || []).includes(canon)) disabledBy.push('config.toml [[skills.config]] enabled=false');
    }
    const profiles = c.tool === 'codex' ? Object.entries(codexOff).filter(([f, l]) => f !== 'config.toml' && l.includes(canon)).map(([f]) => f.replace(/\.config\.toml$/, '')) : [];
    found.push({ tool: c.tool, scope: c.scope, path: toPosix(c.dir), version: ver, disabled: disabledBy.length > 0, disabledBy, disabledOnlyInProfiles: profiles, ...(overrideNote ? { note: overrideNote } : {}) });
  }
  return found;
}

