// ---- tool versions (fixed command strings only) -----------------------------
function version(cmd) {
  // On Windows the CLI is often only reachable through a .cmd/.exe shim (PowerShell may prefer a blocked .ps1).
  const names = IS_WINDOWS ? [cmd, `${cmd}.cmd`, `${cmd}.exe`] : [cmd];
  for (const name of names) {
    const r = IS_WINDOWS ? run(`${name} --version`, [], { shell: true }) : run(name, ['--version']);
    if (r.status === 0 && r.stdout) return r.stdout.split('\n')[0];
  }
  return null;
}
